def main():
    os.makedirs(os.path.join(HERE, 'svg'), exist_ok=True)
    svgs = {'logo': icon_svg(256), 'app-small': marks.app_icon('small'), 'app-tiny': marks.app_icon('tiny'),
            'tray-idle': marks.app_icon('tiny', 'idle'), 'tray-idle-small': marks.app_icon('small', 'idle'),
            'tray-connected': marks.app_icon('tiny', 'connected'), 'tray-connected-small': marks.app_icon('small', 'connected'),
            'wizard-panel': marks.wizard_panel(164, 314)}
    for n in GLYPHS:
        svgs['glyph-' + n] = glyph_svg(n, INK['light'])
    for n, s in svgs.items():
        with open(os.path.join(HERE, 'svg', n + '.svg'), 'w', newline='\n') as f:
            f.write(s + '\n')

    write_ico(os.path.join(ASSETS, 'app.ico'), render([(icon_svg(s), s) for s in ICO_SIZES]))
    for state in ('idle', 'connected'):
        write_ico(os.path.join(ASSETS, 'tray-%s.ico' % state),
                  render([(marks.app_icon('tiny' if s <= 16 else 'small', state), s) for s in TRAY_SIZES]))
    render([(marks.app_icon('small'), 128)])[0].save(os.path.join(ASSETS, 'brand-mark.png'))
    render([(icon_svg(256), 256)])[0].save(os.path.join(ASSETS, 'app-icon.png'))
    write_glyphs_cs()
    wizard = wizard_images()
    if len(sys.argv) > 1:
        preview(sys.argv[1], wizard)


if __name__ == '__main__':
    main()
