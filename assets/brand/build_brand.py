def render(svgs):
    """[(svg, width)] -> [PIL.Image], one node process for the whole batch."""
    js = ("const {Resvg}=require(%s);const fs=require('fs');const jobs=JSON.parse(fs.readFileSync(0));"
          "process.stdout.write(JSON.stringify(jobs.map(([s,w])=>new Resvg(s,{fitTo:{mode:'width',value:w}}).render().asPng().toString('base64'))));") % json.dumps(RESVG)
    out = subprocess.run(['node', '-e', js], input=json.dumps(svgs).encode(), capture_output=True, check=True).stdout
    import base64
    return [Image.open(io.BytesIO(base64.b64decode(b))).convert('RGBA') for b in json.loads(out)]


def icon_svg(size, state='brand'):
    kind = 'tiny' if size <= 16 else 'small' if size < 48 else 'full'
    return marks.app_icon(kind, state)


def write_ico(path, images):
    """32-bit BMP entries (System.Drawing.Icon on .NET Framework reads these at every size), PNG at 256."""
    entries = []
    for im in images:
        w, h = im.size
        if w >= 256:
            b = io.BytesIO(); im.save(b, 'PNG'); data = b.getvalue()
        else:
            px = im.tobytes('raw', 'BGRA')
            rows = [px[y * w * 4:(y + 1) * w * 4] for y in range(h)][::-1]
            mask_row = ((w + 31) // 32) * 4
            data = struct.pack('<IiiHHIIiiII', 40, w, h * 2, 1, 32, 0, w * h * 4, 0, 0, 0, 0) + b''.join(rows) + b'\0' * mask_row * h
        entries.append((w, h, data))
    out = struct.pack('<HHH', 0, 1, len(entries))
    off = 6 + 16 * len(entries)
    for w, h, data in entries:
        out += struct.pack('<BBBBHHII', w % 256, h % 256, 0, 0, 1, 32, len(data), off)
        off += len(data)
    with open(path, 'wb') as f:
        f.write(out + b''.join(d for _, _, d in entries))


def glyph_svg(name, color, inner='#FFFFFF', size=24):
    sw = 2
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="%d" height="%d">' % (size, size)]
    for part in GLYPHS[name]:
        k, d = part[0], part[2:]
        if k == 'f':
            o.append('<path d="%s" fill="%s"/>' % (d, color))
        else:
            o.append('<path d="%s" fill="none" stroke="%s" stroke-width="%g" stroke-linecap="round" stroke-linejoin="round"/>'
                     % (d, inner if k == 'k' else color, sw))
    o.append('</svg>')
    return ''.join(o)


def write_glyphs_cs():
    lines = ['// Generated by assets/brand/build_brand.py from assets/brand/glyphs.py; edit there and rebuild.',
             'using System.Collections.Generic;', '',
             'namespace STGPhantomVPN.Core', '{',
             '    public enum GlyphKind', '    {']
    lines += ['        %s,' % n for n in GLYPHS]
    lines += ['    }', '',
              '    /// <summary>',
              '    /// App glyphs on a 24 unit grid with one 2 unit round stroke. Each part is "s" (stroke), "f" (fill) or',
              '    /// "k" (stroke in the inner brush, e.g. a check knocked out of a filled shield) followed by path data.',
              '    /// </summary>',
              '    public static class GlyphData', '    {',
              '        public const double Grid = 24, Stroke = 2;', '',
              '        public static readonly IReadOnlyDictionary<GlyphKind, string[]> Parts = new Dictionary<GlyphKind, string[]>', '        {']
    for n, parts in GLYPHS.items():
        lines.append('            [GlyphKind.%s] = new[] { %s },' % (n, ', '.join('"%s"' % p for p in parts)))
    lines += ['        };', '    }', '}', '']
    with open(os.path.join(ROOT, 'src', 'STGPhantomVPN', 'Core', 'Glyphs.cs'), 'w', newline='\n') as f:
        f.write('\n'.join(lines))


def wizard_images():
    """Large: teal panel with the white mark and block STG. Small: the app icon on white."""
    big_sizes = [(164, 314), (192, 386), (246, 459), (273, 556), (328, 604)]
    small_sizes = [55, 64, 83, 92, 110]
    jobs = []
    for w, h in big_sizes:
        jobs.append((marks.wizard_panel(w, h), w))
    for s in small_sizes:
        jobs.append((icon_svg(48), int(s * 0.86)))
    ims = render(jobs)
    names = []
    for i, (w, h) in enumerate(big_sizes):
        p = os.path.join(ROOT, 'installer', 'wizard-image-%d.bmp' % (100 + i * 25 if i < 4 else 200))
        ims[i].convert('RGB').save(p)
        names.append(p)
    for j, s in enumerate(small_sizes):
        im = Image.new('RGB', (s, s), 'white')
        ic = ims[len(big_sizes) + j]
        im.paste(ic, ((s - ic.width) // 2, (s - ic.height) // 2), ic)
        im.save(os.path.join(ROOT, 'installer', 'wizard-small-%d.bmp' % (100 + j * 25 if j < 4 else 200)))
    return ims[0]


def font(size, bold=False):
    for p in (['/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'] if bold else ['/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf']):
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def weather_reference():
    """STG Weather's launcher foreground (Android vector) on its blue tile, 64 px; None when the project is absent."""
    import re
    src = os.path.expanduser('~/AndroidStudioProjects/NhiWeather/app/src/main/res/drawable/ic_launcher_foreground.xml')
    if not os.path.exists(src):
        return None
    x = open(src, encoding='utf-8').read()
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="26" fill="#1A73E8"/>']
    for p in re.findall(r'<path(.*?)/>', x, re.S):
        o.append('<path d="%s" fill="%s" fill-rule="%s"/>' % (re.search(r'pathData="(.*?)"', p, re.S).group(1),
                 re.search(r'fillColor="(.*?)"', p).group(1), 'evenodd' if 'evenOdd' in p else 'nonzero'))
    return render([(''.join(o) + '</svg>', 64)])[0]


